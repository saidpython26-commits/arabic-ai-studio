  // Generate ultra-fast offline tutor voice reply
  static getVoiceResponse(userText: string, currentSubject?: string, currentTopic?: string): {
    replyText: string;
    speechText: string;
    suggestedExam?: boolean;
  } {
    const text = userText.trim().toLowerCase();

    // Check for exam intent
    if (text.includes('امتحان') || text.includes('امتحن') || text.includes('اختبر') || text.includes('كويز') || text.includes('quiz') || text.includes('test')) {
      const topicName = currentTopic || 'الموضوع الحالي';
      return {
        replyText: `أهلاً بك يا بطل! أنا جاهز تماماً لامتحانك الآن في "${topicName}". لقد أعددت لك امتحاناً دقيقاً يحتوي على أسئلة اختيار من متعدد مع تقييم فوري وتصحيح نموذجي. اضغط على زر "بدء الامتحان" أو أجبني صوتياً عن أول سؤال!`,
        speechText: `ممتاز يا بطل! أنا جاهز لامتحانك الآن في ${topicName}. استعد وركز معي جيداً!`,
        suggestedExam: true,
      };
    }

    // Check for study/teach intent
    if (text.includes('درس') || text.includes('اشرح') || text.includes('علمني') || text.includes('فهم') || text.includes('قاعدة')) {
      const topicName = currentTopic || 'هذا الدرس';
      return {
        replyText: `يسعدني جداً تدريسك! في درس "${topicName}"، القاعدة الذهبية هي الفهم المتدرج للمفهوم الأساسي ثم تطبيق الأمثلة العملية فوراً. سأشرح لك كل نقطة بوضوح حتى تصبح خبيراً فيها!`,
        speechText: `يسعدني جداً تدريسك يا غالي! في درس ${topicName} سنبدأ بالمفهوم الأساسي خطوة بخطوة حتى تتقنه تماماً.`,
      };
    }

    // Friendly rapid educational response
    const greetings = [
      `أهلاً بك يا مبدع! أنا معلمك الذكي، جاهز لشرح أي مفهوم أو إجراء اختبار حقيقي فوري لك. ما هي المادة أو المسألة التي تود أن ندرسها معاً الآن؟`,
      `أهلاً وسهلاً! استيعابك وتفوقك هدفي الأول. اخبرني بأي درس تريده وسأشرحه لك بأبسط مثال، ثم نخوض امتحاناً سريعاً للتأكد من إتقانك!`,
      `مرحباً بك! أنا معك صوتياً ولحظياً في الرياضيات، العلوم، اللغات، والبرمجة. تفضل بسؤالي وسأجيبك بأعلى سرعة!`
    ];
    const picked = greetings[Math.floor(Math.random() * greetings.length)];

    return {
      replyText: picked,
      speechText: picked,
    };
  }
